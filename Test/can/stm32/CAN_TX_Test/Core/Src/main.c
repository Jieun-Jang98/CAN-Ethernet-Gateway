/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_CAN1_Init();
  /* USER CODE BEGIN 2 */
TxHeader.StdId = 0x100;
  TxHeader.IDE = CAN_ID_STD;
  TxHeader.RTR = CAN_RTR_DATA;
  TxHeader.DLC = 4;
  TxHeader.TransmitGlobalTime = DISABLE;

  /* Pause CAN as well when the debugger halts the CPU. */
  __HAL_DBGMCU_FREEZE_CAN1();
  if (HAL_CAN_Start(&hcan1) != HAL_OK)
  {
    Error_Handler();
  }
  last_tx_tick = HAL_GetTick() - 100U;
/* USER CODE END 2 */

  /* Initialize leds */
  BSP_LED_Init(LED2);

  /* Initialize USER push-button, will be used to trigger an interrupt each time it's pressed.*/
  BSP_PB_Init(BUTTON_USER, BUTTON_MODE_EXTI);

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
/* Only one outstanding request; count completion before reusing it. */
    if (tx_pending && !HAL_CAN_IsTxMessagePending(&hcan1, TxMailbox))
    {
      if (__HAL_CAN_GET_FLAG(&hcan1, tx_ok_flag))
      {
        tx_complete_count++;
        BSP_LED_Toggle(LED2);
      }
      else
      {
        tx_failed_count++;
      }
      __HAL_CAN_CLEAR_FLAG(&hcan1, tx_complete_flag);
      tx_pending = 0;
    }

    uint32_t now = HAL_GetTick();
    if (!tx_pending && (uint32_t)(now - last_tx_tick) >= 100U)
    {
      last_tx_tick = now;
      if (HAL_CAN_AddTxMessage(&hcan1, &TxHeader, TxData, &TxMailbox) == HAL_OK)
      {
        tx_count++;
        tx_pending = 1;
        if (TxMailbox == CAN_TX_MAILBOX0)
        {
          tx_ok_flag = CAN_FLAG_TXOK0;
          tx_complete_flag = CAN_FLAG_RQCP0;
        }
        else if (TxMailbox == CAN_TX_MAILBOX1)
        {
          tx_ok_flag = CAN_FLAG_TXOK1;
          tx_complete_flag = CAN_FLAG_RQCP1;
        }
        else
        {
          tx_ok_flag = CAN_FLAG_TXOK2;
          tx_complete_flag = CAN_FLAG_RQCP2;
        }
      }
      else
      {
        tx_failed_count++;
      }
    }

    can_error = HAL_CAN_GetError(&hcan1);
    can_esr = hcan1.Instance->ESR;
    tx_free = HAL_CAN_GetTxMailboxesFreeLevel(&hcan1);
    HAL_Delay(1);
  }
/* USER CODE END 3 */
}

